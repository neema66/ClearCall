"""
Real-time evaluation harness for the ClearCall / senhance pipeline.

Runs a filter/pipeline through SimpleAudioEngine exactly the way the
live GUI does (same process_audio() call, same block size), against a
clean reference WAV -- either paired with a real noisy recording, or
with synthetic noise generated by the engine itself (white/pink/brown/
background file, same as the GUI's Noise Type dropdown).

Produces the two groups of metrics from the "Real-Time Evaluation"
slide:

  Performance (is it fast enough to run live)
    - latency        : mean/p95/max wall-clock time to process one
                        block, vs. the block's real-time duration
    - real-time factor (RTF) : total processing time / total audio
                        duration. Must stay below 1.0 or the pipeline
                        can't keep up with the mic in real time.
    - cpu usage       : process CPU time / wall-clock time during the
                        run, as a percentage (can exceed 100% if the
                        pipeline itself is multi-threaded)
    - dropout rate    : fraction of blocks that took longer to
                        process than their real-time duration -- each
                        one is a buffer underrun waiting to happen

  Quality (does it actually sound better)
    - SNR improvement : enhanced vs. noisy signal-to-noise ratio, dB
    - SI-SDR          : scale-invariant signal-to-distortion ratio, dB
    - PESQ            : ITU-T P.862 perceptual quality score (needs
                        the `pesq` package)
    - STOI            : short-time objective intelligibility (needs
                        the `pystoi` package)

Usage:

    # Synthesize noise from a clean recording (same as GUI's noise
    # controls) and evaluate a filter against it:
    python benchmark_eval.py --clean my_voice.wav --filter lowpass \\
        --noise-type pink --noise-db -20

    # Evaluate against a real noisy recording (paired with its clean
    # reference, e.g. a "clean" and "noisy" take of the same clip):
    python benchmark_eval.py --clean clean.wav --noisy noisy.wav \\
        --filter improved_dsp --dsp-config config/improved_dsp.yaml

    # Compare every filter type against the same noisy signal in one
    # run:
    python benchmark_eval.py --clean my_voice.wav --noise-type white \\
        --noise-db -15 --filter all

Run with --help for the full flag list. Writes a JSON report and, by
default, the synthesized noisy / enhanced WAVs so you can listen to
them (--no-audio-out to skip that).
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from math import gcd
from pathlib import Path

import numpy as np

try:
    import psutil
except ImportError:
    psutil = None

from senhance.experiments.simple_filter import SimpleAudioEngine


FILTER_CHOICES = [
    "none",
    "lowpass",
    "highpass",
    "bandpass",
    "original_dsp",
    "improved_dsp",
]

# CLI-facing name -> engine's internal filter_type string
FILTER_NAME_MAP = {
    "original_dsp": "dsp_pipeline",
    "improved_dsp": "improved_dsp",
}


NOISE_TYPE_CHOICES = ["white", "pink", "brown", "background"]


# ============================================================
# Audio I/O
# ============================================================


def load_wav(path, target_sr):

    try:

        import soundfile as sf

        data, sr = sf.read(path, always_2d=False)

        data = data.astype(np.float64)

    except ImportError:

        from scipy.io import wavfile

        sr, data = wavfile.read(path)

        if np.issubdtype(data.dtype, np.integer):

            data = data.astype(np.float64) / np.iinfo(data.dtype).max

        else:

            data = data.astype(np.float64)


    if data.ndim > 1:

        data = data.mean(axis=1)


    if sr != target_sr:

        from scipy.signal import resample_poly

        g = gcd(int(sr), int(target_sr))

        data = resample_poly(data, target_sr // g, sr // g)


    return data.astype(np.float32)



def save_wav(path, audio, sr):

    try:

        import soundfile as sf

        sf.write(str(path), audio, sr)

    except ImportError:

        from scipy.io import wavfile

        clipped = np.clip(audio, -1.0, 1.0)

        wavfile.write(str(path), sr, (clipped * 32767).astype(np.int16))



def match_length(*signals):

    n = min(len(s) for s in signals)

    return [s[:n] for s in signals]



def resample_to(audio, src_sr, dst_sr):

    if src_sr == dst_sr:

        return audio

    from scipy.signal import resample_poly

    g = gcd(int(src_sr), int(dst_sr))

    return resample_poly(audio, dst_sr // g, src_sr // g).astype(np.float32)



# ============================================================
# Running audio through the engine, block by block, timed
# ============================================================


def build_engine(args, filter_name):

    engine = SimpleAudioEngine()

    engine.sample_rate = args.sample_rate

    engine.block_size = args.block_size


    if args.config:

        engine.set_config_path(args.config)

    if args.dsp_config:

        engine.set_improved_dsp_config_path(args.dsp_config)


    engine.set_cutoffs(args.cutoff_low, args.cutoff_high)

    engine.set_filter_order(args.order)


    internal_type = FILTER_NAME_MAP.get(filter_name, filter_name)

    engine.set_filter_type(internal_type)


    return engine



def run_through_engine(engine, audio, block_size, undo_mix_gain=True):

    # process_audio() always applies a *0.5 gain meant for two-mic
    # mixing in the live GUI. For offline single-signal evaluation we
    # cancel it by pre-multiplying by 2 so what we measure is the
    # filter/pipeline's own effect, not an extra unintended -6dB pad.

    gain = 2.0 if undo_mix_gain else 1.0

    n = len(audio)

    out = np.zeros(n, dtype=np.float32)

    timings = []


    for start in range(0, n, block_size):

        end = min(start + block_size, n)

        block = audio[start:end]

        if len(block) < block_size:

            block = np.pad(block, (0, block_size - len(block)))


        t0 = time.perf_counter()

        processed = engine.process_audio(block * gain)

        t1 = time.perf_counter()

        timings.append(t1 - t0)


        out[start:end] = processed[: end - start]


    return out, np.array(timings)



def synthesize_noisy(clean, args):

    # Uses the engine's own noise generator (same code path as the
    # GUI's Noise Type dropdown) so the synthetic noise matches what
    # you'd hear live, then mixes it with the clean signal exactly the
    # way process_audio() does (audio + noise, no filtering).

    noise_engine = SimpleAudioEngine()

    noise_engine.sample_rate = args.sample_rate

    noise_engine.block_size = args.block_size

    noise_engine.set_filter_type("none")

    noise_engine.add_noise_enabled = True

    noise_engine.noise_only = False

    noise_engine.set_noise_type(args.noise_type)

    noise_engine.set_noise_level(args.noise_db)


    if args.noise_type == "background":

        if not args.background_file:

            raise SystemExit(
                "--noise-type background requires --background-file "
                "pointing at an ambience recording (e.g. a coffee shop "
                "loop)."
            )

        noise_engine.set_background_file(args.background_file)


    noisy, _ = run_through_engine(
        noise_engine,
        clean,
        args.block_size,
    )

    return noisy



