def evaluate_one_filter(filter_name, clean, noisy, args, out_dir):

    print("\n=== filter: %s ===" % filter_name)

    engine = build_engine(args, filter_name)


    def _run():

        return run_through_engine(
            engine,
            noisy,
            args.block_size,
        )


    (enhanced, timings), cpu_info = measure_cpu(_run)


    perf = performance_metrics(
        timings,
        args.block_size,
        args.sample_rate,
    )

    perf.update(cpu_info)


    quality = quality_metrics(
        clean,
        noisy,
        enhanced,
        args.sample_rate,
        max_shift_ms=args.max_shift_ms,
    )


    if not args.no_audio_out:

        save_wav(
            out_dir / ("enhanced_%s.wav" % filter_name),
            enhanced,
            args.sample_rate,
        )


    report = {
        "filter": filter_name,
        "performance": perf,
        "quality": quality,
    }


    print_report(report)


    return report



def print_report(report):

    perf = report["performance"]

    quality = report["quality"]


    print("  -- performance --")

    print(
        "  latency (mean/p95/max): %.2f / %.2f / %.2f ms  "
        "(block = %.2f ms)"
        % (
            perf["latency_mean_ms"],
            perf["latency_p95_ms"],
            perf["latency_max_ms"],
            perf["block_duration_ms"],
        )
    )

    print("  real-time factor: %.3fx  (<1.0 = keeps up live)" % perf["real_time_factor"])

    cpu_str = (
        "%.1f%%" % perf["cpu_usage_pct"]
        if perf.get("cpu_usage_pct") is not None
        else "n/a (%s)" % perf.get("cpu_error")
    )

    print("  cpu usage: %s" % cpu_str)

    print("  dropout rate: %.2f%%" % perf["dropout_rate_pct"])


    print("  -- quality --")

    print(
        "  SNR: noisy %.2f dB -> enhanced %.2f dB  (%+0.2f dB)"
        % (
            quality["snr_noisy_db"],
            quality["snr_enhanced_db"],
            quality["snr_improvement_db"],
        )
    )

    print(
        "  SI-SDR: noisy %.2f dB -> enhanced %.2f dB  (%+0.2f dB)"
        % (
            quality["si_sdr_noisy_db"],
            quality["si_sdr_enhanced_db"],
            quality["si_sdr_improvement_db"],
        )
    )

    if quality["pesq"] is not None:

        print("  PESQ: %.3f / 4.5" % quality["pesq"])

    else:

        print("  PESQ: n/a (%s)" % quality["pesq_error"])


    if quality["stoi"] is not None:

        print("  STOI: %.3f / 1.0" % quality["stoi"])

    else:

        print("  STOI: n/a (%s)" % quality["stoi_error"])



def parse_args():

    parser = argparse.ArgumentParser(
        description="Measure real-time performance and enhancement "
        "quality for a senhance filter/pipeline.",
    )


    parser.add_argument(
        "--clean", required=True,
        help="Path to a clean (dry) reference recording."
    )

    parser.add_argument(
        "--noisy", default=None,
        help="Path to a matching noisy recording. If omitted, noise is "
        "synthesized from --clean using --noise-type / --noise-db "
        "(same generators as the GUI)."
    )


    parser.add_argument(
        "--filter", default="none", choices=FILTER_CHOICES + ["all"],
        help="Which filter/pipeline to evaluate. 'all' runs every "
        "choice in one report."
    )

    parser.add_argument("--config", default=None, help="config/*.yaml for original_dsp.")
    parser.add_argument("--dsp-config", default=None, help="config/improved_dsp.yaml for improved_dsp.")
    parser.add_argument("--cutoff-low", type=float, default=300)
    parser.add_argument("--cutoff-high", type=float, default=3400)
    parser.add_argument("--order", type=int, default=4)


    parser.add_argument("--noise-type", default="white", choices=NOISE_TYPE_CHOICES)
    parser.add_argument("--noise-db", type=float, default=-20)
    parser.add_argument(
        "--background-file", default=None,
        help="Ambience recording to loop when --noise-type background "
        "(e.g. a coffee shop recording)."
    )


    parser.add_argument("--sample-rate", type=int, default=48000)

    parser.add_argument(
        "--max-shift-ms", type=float, default=30.0,
        help="Search window (ms) for aligning enhanced audio to the "
        "clean reference before scoring SNR/SI-SDR, to correct for "
        "STFT pipeline delay (default covers hop sizes up to ~1440 "
        "samples @ 48kHz; widen this if frame_size/hop_size in your "
        "config is unusually large)."
    )
    parser.add_argument("--block-size", type=int, default=480)


    parser.add_argument("--out-dir", default="eval_out")

    parser.add_argument(
        "--no-audio-out", action="store_true",
        help="Skip writing the noisy/enhanced WAVs, JSON report only."
    )


    return parser.parse_args()



def main():

    args = parse_args()


    out_dir = Path(args.out_dir)

    out_dir.mkdir(parents=True, exist_ok=True)


    clean = load_wav(args.clean, args.sample_rate)


    if args.noisy:

        noisy = load_wav(args.noisy, args.sample_rate)

        clean, noisy = match_length(clean, noisy)

    else:

        noisy = synthesize_noisy(clean, args)

        clean, noisy = match_length(clean, noisy)


    if not args.no_audio_out:

        save_wav(out_dir / "clean.wav", clean, args.sample_rate)

        save_wav(out_dir / "noisy.wav", noisy, args.sample_rate)


    filters_to_run = (
        FILTER_CHOICES if args.filter == "all" else [args.filter]
    )


    reports = []

    for filter_name in filters_to_run:

        try:

            reports.append(
                evaluate_one_filter(filter_name, clean, noisy, args, out_dir)
            )

        except Exception as e:

            import traceback

            traceback.print_exc()

            print(
                "!! skipping '%s': %s" % (filter_name, e)
            )

            reports.append({
                "filter": filter_name,
                "error": str(e),
            })


    report_path = out_dir / "report.json"

    with open(report_path, "w") as f:

        json.dump(reports, f, indent=2)


    print("\nWrote %s" % report_path)

    if not args.no_audio_out:

        print("Wrote clean/noisy/enhanced WAVs to %s" % out_dir)



if __name__ == "__main__":

    main()