# Quality metrics
# ============================================================


def si_sdr(reference, estimate, eps=1e-9):

    reference = reference.astype(np.float64)

    estimate = estimate.astype(np.float64)


    alpha = np.dot(estimate, reference) / (
        np.dot(reference, reference) + eps
    )

    target = alpha * reference

    residual = estimate - target


    return 10 * np.log10(
        (np.sum(target ** 2) + eps) / (np.sum(residual ** 2) + eps)
    )



def snr_db(reference, estimate, eps=1e-9):

    reference = reference.astype(np.float64)

    estimate = estimate.astype(np.float64)


    noise = estimate - reference


    return 10 * np.log10(
        (np.sum(reference ** 2) + eps) / (np.sum(noise ** 2) + eps)
    )



def normalize_peak(*signals, target_peak=0.7):

    peak = max(
        float(np.max(np.abs(s))) for s in signals
    )

    if peak < 1e-9:

        return signals

    scale = target_peak / peak

    return [s * scale for s in signals]



def try_pesq(clean, degraded, sr):

    try:

        from pesq import pesq

    except ImportError:

        return None, "pesq not installed (pip install pesq)"


    pesq_sr = 16000

    mode = "wb"

    c = resample_to(clean, sr, pesq_sr)

    d = resample_to(degraded, sr, pesq_sr)

    c, d = match_length(c, d)


    try:

        score = pesq(pesq_sr, c, d, mode)

        return float(score), None

    except Exception as e:

        return None, str(e)



def try_stoi(clean, degraded, sr):

    try:

        from pystoi import stoi

    except ImportError:

        return None, "pystoi not installed (pip install pystoi)"


    c, d = match_length(clean, degraded)


    try:

        score = stoi(c, d, sr, extended=False)

        return float(score), None

    except Exception as e:

        return None, str(e)



def align_to_reference(reference, estimate, max_shift_samples):

    # STFT-based pipelines (DSPPipeline / ImprovedDSPPipeline) buffer
    # a frame or two before their first output, so "enhanced" is
    # delayed relative to "clean" by some number of samples. SI-SDR
    # and plain SNR are both very sensitive to that kind of shift --
    # even a few dozen samples of misalignment tanks the score even
    # though the audio itself is fine -- so find the best-matching
    # shift via cross-correlation and align before scoring.
    #
    # Positive shift = estimate lags reference (needs to be pulled
    # earlier); negative = estimate leads.

    reference = reference.astype(np.float64)

    estimate = estimate.astype(np.float64)


    from scipy.signal import correlate

    correlation = correlate(
        estimate,
        reference,
        mode="full",
        method="fft",
    )

    # correlation[k] corresponds to shift = k - (len(reference) - 1)

    lags = np.arange(-max_shift_samples, max_shift_samples + 1)

    center = len(reference) - 1

    window = correlation[center - max_shift_samples: center + max_shift_samples + 1]

    best_shift = int(lags[np.argmax(window)])


    if best_shift > 0:

        # estimate lags -- drop its leading edge, pad the reference's
        # tail so lengths still line up for scoring.

        aligned_estimate = estimate[best_shift:]

        aligned_reference = reference[: len(aligned_estimate)]

    elif best_shift < 0:

        aligned_estimate = estimate[: best_shift]

        aligned_reference = reference[-best_shift:][: len(aligned_estimate)]

    else:

        aligned_estimate = estimate

        aligned_reference = reference


    n = min(len(aligned_reference), len(aligned_estimate))

    return (
        aligned_reference[:n].astype(np.float32),
        aligned_estimate[:n].astype(np.float32),
        best_shift,
    )



def quality_metrics(clean, noisy, enhanced, sr, max_shift_ms=30.0):

    clean_n, noisy_n, enhanced_n = normalize_peak(clean, noisy, enhanced)


    max_shift_samples = int(sr * max_shift_ms / 1000)


    clean_for_noisy, noisy_aligned, noisy_shift = align_to_reference(
        clean_n, noisy_n, max_shift_samples
    )

    clean_for_enhanced, enhanced_aligned, enhanced_shift = align_to_reference(
        clean_n, enhanced_n, max_shift_samples
    )


    noisy_si_sdr = si_sdr(clean_for_noisy, noisy_aligned)

    enhanced_si_sdr = si_sdr(clean_for_enhanced, enhanced_aligned)


    noisy_snr = snr_db(clean_for_noisy, noisy_aligned)

    enhanced_snr = snr_db(clean_for_enhanced, enhanced_aligned)


    # PESQ/STOI are far less sensitive to small shifts (they're
    # perceptual/short-time measures, not sample-exact), but align
    # the enhanced signal too for consistency.

    pesq_score, pesq_err = try_pesq(clean_for_enhanced, enhanced_aligned, sr)

    stoi_score, stoi_err = try_stoi(clean_for_enhanced, enhanced_aligned, sr)


    return {
        "snr_noisy_db": round(noisy_snr, 2),
        "snr_enhanced_db": round(enhanced_snr, 2),
        "snr_improvement_db": round(enhanced_snr - noisy_snr, 2),
        "si_sdr_noisy_db": round(noisy_si_sdr, 2),
        "si_sdr_enhanced_db": round(enhanced_si_sdr, 2),
        "si_sdr_improvement_db": round(enhanced_si_sdr - noisy_si_sdr, 2),
        "pesq": round(pesq_score, 3) if pesq_score is not None else None,
        "pesq_error": pesq_err,
        "stoi": round(stoi_score, 3) if stoi_score is not None else None,
        "stoi_error": stoi_err,
        "noisy_alignment_shift_samples": noisy_shift,
        "enhanced_alignment_shift_samples": enhanced_shift,
    }



