# Performance metrics
# ============================================================


def performance_metrics(timings, block_size, sample_rate):

    block_duration = block_size / sample_rate


    total_audio_s = len(timings) * block_duration

    total_processing_s = float(np.sum(timings))


    dropout_rate = float(
        np.mean(timings > block_duration)
    )


    return {
        "block_size": block_size,
        "sample_rate": sample_rate,
        "block_duration_ms": round(block_duration * 1000, 3),
        "latency_mean_ms": round(float(np.mean(timings)) * 1000, 3),
        "latency_p95_ms": round(
            float(np.percentile(timings, 95)) * 1000, 3
        ),
        "latency_max_ms": round(float(np.max(timings)) * 1000, 3),
        "real_time_factor": round(
            total_processing_s / total_audio_s, 4
        ),
        "dropout_rate_pct": round(dropout_rate * 100, 3),
        "total_audio_s": round(total_audio_s, 2),
        "total_processing_s": round(total_processing_s, 4),
    }



def measure_cpu(fn):

    if psutil is None:

        result = fn()

        return result, {
            "cpu_usage_pct": None,
            "cpu_error": "psutil not installed (pip install psutil)",
        }


    process = psutil.Process()

    cpu_before = process.cpu_times()

    wall_t0 = time.perf_counter()


    result = fn()


    wall_t1 = time.perf_counter()

    cpu_after = process.cpu_times()


    cpu_seconds = (
        (cpu_after.user + cpu_after.system)
        - (cpu_before.user + cpu_before.system)
    )

    wall_seconds = wall_t1 - wall_t0


    cpu_pct = (
        (cpu_seconds / wall_seconds) * 100
        if wall_seconds > 0 else None
    )


    return result, {
        "cpu_usage_pct": round(cpu_pct, 1) if cpu_pct is not None else None,
        "cpu_error": None,
    }



